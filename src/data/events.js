// ICIS, CIST, WISE, WITS lead the chip row and directory; the rest keep their
// original order (Array.prototype.sort is stable).
const FRONT_ORDER = ['icis-2026', 'cist-2026', 'wise-2026', 'wits-2026'];

export const eventGroups = [...conferenceGroups].sort((a, b) => {
  const rank = (group) => {
    const index = FRONT_ORDER.indexOf(group.id);
    return index === -1 ? FRONT_ORDER.length : index;
  };
  return rank(a) - rank(b);
});

export function flattenEvents(groups = eventGroups) {
  return groups.flatMap((group) =>
    group.events.map((event) => ({
      ...event,
      id: `${group.id}:${event.id}`,
      localId: event.id,
      groupId: group.id,
      acronym: group.acronym,
      conferenceName: group.name,
      theme: group.theme,
      location: event.location || group.location,
      website: group.website,
      sourceUrl: group.sourceUrl,
      sourceLabel: group.sourceLabel,
      sourceChecked: group.sourceChecked,
      color: group.color,
    })),
  );
}

// The primary conference event for a group (the multi-day meeting itself),
// used for map markers and the detail header. Falls back to the earliest event.
export function conferenceEvent(group) {
  return group.events.find((event) => event.kind === 'conference') || group.events[0];
}
